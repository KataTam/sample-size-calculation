check_model_answers <- function() {
  source("R/model_answers.R", local = TRUE)
  source("R/sample_size_functions.R", local = TRUE)
  source("R/activity_bridge.R", local = TRUE)
  source("R/teaching_cases.R", local = TRUE)
  has <- function(text, value) stopifnot(grepl(value, text, fixed = TRUE))
  x <- recruitment_plan(56, .20, .10)
  has(recruitment_model_answer(x, FALSE, FALSE), "70 per group (140 total)")
  has(recruitment_model_answer(x, FALSE, TRUE), "already includes")
  x <- recruitment_plan(100, .05, .10, .10, .05)
  has(recruitment_model_answer(x, TRUE, FALSE), "154 per group (308 total)")
  has(sampling_model_answer(normal_sampling_operating_characteristics(mu1 = 115)), "reduces power")
  has(sampling_model_answer(normal_sampling_operating_characteristics(mu1 = 120)), "false-positive probability")
  has(sampling_model_answer(normal_sampling_operating_characteristics(mu1 = 115, sidedness = "two.sided")), "increases power")
  v <- list(goal = "fixed", anticipated_p = .8, full_width = .2, confidence = .90, unknown_p = TRUE, fixed_n = 40, dropout = .2)
  p <- proportion_precision_plan(v$anticipated_p, v$full_width, v$confidence, v$unknown_p, v$dropout)
  answer <- precision_model_answer(v, p, 40, "pilot_feasibility")
  has(answer, "retention pilot"); has(answer, "90% confidence"); has(answer, "fixed at 40")
  has(answer, "planning uses 50%"); has(answer, "simulation assumes 80%"); has(answer, "target is 50")
  has(answer, "unknown retention status"); has(answer, "values leading to different decisions"); has(answer, "available participants, time, and resources")
  has(recruitment_model_answer(x, TRUE, FALSE), "comparable follow-up evidence")
  has(lab_question_help("prediction"), "prediction horizon"); stopifnot(!grepl("PICO", lab_question_help("prediction")))
  has(lab_question_help("diagnostic"), "reference standard")
  has(lab_question_help("two_groups"), "independent observations")
  stopifnot(grepl('placeholder="Your answer"', as.character(activity_text_input("sample", "Question", "Example answer", "Help")), fixed = TRUE))
  for (id in c("pain_one_many", "discharge", "adherence", "rehabilitation", "mean_precision", "own_study")) {
    v <- validate_lab_inputs(teaching_case(id)$inputs)
    x <- teaching_case_spec(id); x$n <- plan_n(x, v$goal, v$target_power)
    a <- lab_model_answers(v, study_input_defaults(), id, x, list(recruits = 168, balanced = 168))
    has(a$justification, paste(x$n, "participants per group"))
    if (v$goal != "precision") has(a$justification, format_percent(spec_power(x), 1))
    if (v$goal != "testing") has(a$justification, model_effect(anticipated_width(x), x$outcome))
    has(a$evidence_sources, model_effect(true_difference(x), x$outcome))
    has(a$evidence_sources, "assessment time"); has(a$evidence_sources, "uncertainty of [range]")
    has(a$clinical_relevance, "Patient or clinical input")
    has(a$justification, "sensitivity results")
    if (id == "adherence") { has(a$study_question, "probiotic"); stopifnot(!grepl("pain", paste(a, collapse = " "))) }
    if (id == "discharge") { has(a$study_question, "discharged"); stopifnot(!grepl("pain", paste(a, collapse = " "))) }
    if (id == "rehabilitation") has(a$study_question, "six weeks")
  }
  details <- study_input_defaults(); details$study_design <- "paired"
  a <- lab_model_answers(lab_input_defaults(), details, "discharge")
  has(a$study_question, "paired"); has(a$justification, "matching planning method")
  # The native server uses the same reactive result that populates the tables.
  old <- getwd(); on.exit(setwd(old)); setwd("apps/power_explorer")
  app <- new.env(parent = globalenv()); sys.source("app.R", envir = app)
  shiny::testServer(app$server, {
    do.call(session$setInputs, lab_input_defaults())
    session$setInputs(justification = "My own answer", run_one = 0, run_many = 0)
    has(model_answers()$justification, "45 participants per group")
    session$setInputs(goal = "fixed", fixed_n = 17, target_power = .9, dropout = .2)
    has(model_answers()$justification, "17 participants per group (34 total)")
    has(model_answers()$justification, "22 recruits per group (44 total)")
    has(model_answers()$justification, "misses the power and interval-width targets")
    stopifnot(input$justification == "My own answer")
    session$setInputs(B = 100, run_many = 1)
    has(model_answers()$justification, "saved batch of 100")
    session$setInputs(plan_delta = 2)
    has(model_answers()$justification, "earlier inputs")
    session$setInputs(run_many = 2)
    stopifnot(!grepl("earlier inputs", model_answers()$justification))
    session$setInputs(outcome = "proportions", missing_mode = "selective", missing_n = 60, show_advanced = TRUE, run_many = 3)
    has(output$many_model_answer, "60 recruited")
    has(output$many_model_answer, "bias and coverage")
    stopifnot(!grepl("nominal probability stays", output$many_model_answer))
    session$setInputs(study_design = "paired")
    has(model_answers()$justification, "matching planning method")
  })
  message("Model answers: current calculations, case context, one-sided direction, fixed samples, saved simulations and learner text checks passed.")
}
if (identical(environment(), globalenv())) check_model_answers()
