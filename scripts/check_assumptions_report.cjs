    await page.locator('#goal').selectOption('feasibility');
    await page.locator('#progression').fill('Retention among enrolled participants; justify proceed, amend or stop criteria');
    assert.match(await page.locator('#report').innerText(), /Retention among enrolled participants/);
    await page.locator('#plan-identity').evaluate(el=>el.open=true);
    await page.locator('#plan-basis').selectOption('pain');
    await page.locator('#example').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('The research question'));
    await openSections();
    for (const id of ['expected','planning','clinical','counts','recruitment']) assert.equal(await page.locator('#'+id).inputValue(),'');
    assert.match(await page.locator('#question').inputValue(), /standard treatment/);
    assert.equal(await page.locator('#outcome_detail').inputValue(), 'Pain relief (yes/no) at four weeks');
    await page.locator('#expected').fill('40 percentage points, supported by the illustrative pilot');
    await page.locator('#planning').fill('30 percentage points, selected for planning');
    await page.locator('#clinical').fill('20 percentage points, with clinical justification needed');
    await page.locator('#counts').fill('56 per group, 112 total');
    await page.locator('#recruitment').fill('63 per group, 126 in total');
    assert.equal(await page.locator('#study_type').inputValue(), 'comparison');
    assert.equal(await page.locator('#software').inputValue(), '');
    for(const input of await page.locator('textarea:visible').all())if(!await input.inputValue())await input.fill('A decision recorded by the learner');
    assert.match(await page.locator('#progress').innerText(), /All \d+ prompts answered/);
    fs.mkdirSync('build', {recursive: true});
    await page.screenshot({path: 'build/assumptions-report-desktop.png'});
    await page.locator('#question').fill('<img src=x onerror="window.injected=true">');
    assert.equal(await page.locator('#report img').count(), 0);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    const {html:savedHTML} = await saveReportPair(page,page,'#save','#save-word','study-plan');
    let pending = page.waitForEvent('download'); await page.locator('#save-work').click();
    const saved = await pending;
    assert.equal(saved.suggestedFilename(), 'study-plan-work.json');
    const document = JSON.parse(fs.readFileSync(await saved.path(), 'utf8'));
    assert.equal(document.version, 3);
    assert.equal(document.entries.question,await page.locator('#question').inputValue());
    assert(!('summary' in document.entries) && !('calculation_summary' in document.entries),'Only one set of answers is saved');
    assert(!savedHTML.includes('study-plan-data'), 'Readable reports contain no embedded backup');
    const offline = await context.newPage();
    await offline.setContent(savedHTML);
    assert.match(await offline.locator('body').innerText(), /40 percentage points/);
    assert.deepEqual(await offline.locator('body > h2').allTextContents(),['Sample size calculation report','Supporting study plan']);
    assert(savedHTML.indexOf('<h2>Sample size calculation report</h2>')<savedHTML.indexOf('<h2>Supporting study plan</h2>'));
    assert.match(await offline.locator('body').innerText(), /SPIRIT 2025/);
    assert.match(await offline.locator('body').innerText(), /Prepared chronic pain calculation/);
    assert.match(await offline.locator('body').innerText(), /Software: R.*stats.*source version/);
    assert.match(await offline.locator('body').innerText(), /5%.*59 per group, 118 total/);
    assert.match(await offline.locator('body').innerText(), /8A.35851/);
    assert.doesNotMatch(await offline.locator('body').innerText(), /"schema"/);
    assert.equal(await offline.locator('img').count(), 0);
    assert.equal(await offline.evaluate(() => window.injected), undefined);
    await offline.close();
    assert.equal(document.entries.expected.slice(0, 2), '40');
    await page.locator('#clear').click(); assert.equal(await page.locator('#question').inputValue(), '');
    assert.match(await page.locator('#plan-section-0 .section-progress').innerText(), /^0 of \d+ answered$/);
    await page.locator('#restore').setInputFiles({name: 'study-plan-report.html', mimeType: 'text/html', buffer: Buffer.from(savedHTML.replace('</body>', '<script type="application/json" id="study-plan-data">'+JSON.stringify(document)+'</script></body>'))});
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Saved entries restored.');
    assert.equal(await page.locator('#question').inputValue(), document.entries.question);
    const legacy = {schema: document.schema, version: 1, entries: {...document.entries}};
    for (const id of ['population', 'intervention', 'comparator', 'plan_level']) delete legacy.entries[id];
    await page.locator('#restore').setInputFiles({name: 'old-entries.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy))});
    await page.waitForFunction(() => document.querySelector('#population').value === '');
    assert.equal(await page.locator('#question').inputValue(), legacy.entries.question);
    assert.equal(await page.locator('#intervention').inputValue(), '');
    const large = {...document, entries: {...document.entries}};
    for (const name of Object.keys(large.entries)) if (!['study_type', 'outcome', 'goal','plan_title','plan_basis','plan_level','decision_statuses','calculation_records'].includes(name)) large.entries[name] = '漢'.repeat(5000);
    assert.ok(Buffer.byteLength(JSON.stringify(large)) > 100000);
    await page.locator('#restore').setInputFiles({name: 'large.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(large))});
    await page.waitForFunction(() => document.querySelector('#question').value.length === 5000);
    assert.equal(await page.locator('#question').inputValue(), large.entries.question);
    await page.locator('#restore').setInputFiles({name: 'study-plan.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(document))});
    await page.waitForFunction(() => document.querySelector('#question').value.startsWith('<img'));
    await page.locator('#restore').setInputFiles({name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({...document, entries: {...document.entries, goal: 'unsupported'}}))});
    await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('Entries were not changed.'));
    assert.equal(await page.locator('#question').inputValue(), document.entries.question);
    pending = page.waitForEvent('download'); await page.locator('#download-text').click();
    const report = await pending, reportText = fs.readFileSync(await report.path(), 'utf8');
    assert.match(reportText, /40 percentage points/); assert.match(reportText, /63 per group, 126 in total/);
    // The two-panel lesson and activity registry are generated by the site build.
    if (process.argv.includes('--source')) {
      assert.deepEqual(errors,[]);
      console.log('Study-plan source checks passed: one answer set, concise/supporting sections, current edits, goal changes, safe text, saved work and PDF/Word exports.');
      return;
    }
    await page.goto(base + 'study/?activity=assumptions_report');
    await page.waitForFunction(() => document.querySelector('#app-status').textContent.startsWith('App loaded'));
    const activity = page.frameLocator('#app-frame');
    await activity.locator('#resume-plan-button').click();
    assert.equal(await activity.locator('#question').inputValue(), document.entries.question);
    const separate = await page.locator('#app-separate').getAttribute('href');
    assert.ok(!separate.includes('state='), 'Written answers must not be added to the URL');
    assert.match(await page.locator('#lesson-frame').getAttribute('src'), /#record-assumptions$/);
    await activity.locator('#question').fill('Keep this plan while navigating the tutorial');
    await page.locator('#close-app-panel').focus();
