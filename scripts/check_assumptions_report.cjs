    assert.equal(await page.locator('#app-pane').isVisible(), false);
    assert.equal(await page.locator('#panel-separator').isVisible(), false);
    assert.equal(await page.locator(':focus').getAttribute('data-view'), 'lesson');
    assert.ok((await page.locator('#lesson-pane').boundingBox()).width >= 0.98 * page.viewportSize().width);
    await page.locator('button[data-view="both"]').click();
    assert.equal(await page.locator('#app-pane').isVisible(), true);
    assert.equal(await activity.locator('#question').inputValue(), 'Keep this plan while navigating the tutorial');
    await page.screenshot({path: 'build/assumptions-report-two-panel.png'});
    const lesson = page.frameLocator('#lesson-frame');
    await lesson.getByRole('link', {name:'Toggle Sidebar', exact:true}).click();
    await lesson.locator('.book-summary a[href="calculations.html"]').first().click();
