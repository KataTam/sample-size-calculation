check_app_reports <- function() {
  root <- getwd(); on.exit(setwd(root))
  source("R/sample_size_functions.R", local = TRUE)
  source("R/activity_bridge.R", local = TRUE)
  source("R/app_presentation.R", local = TRUE)
  has <- function(text, value) stopifnot(any(grepl(value, text, fixed = TRUE)))
  lacks <- function(text, value) stopifnot(!any(grepl(value, text, fixed = TRUE)))
  app_server <- function(slug) {
    setwd(file.path(root, "apps", slug))
    env <- new.env(parent = globalenv()); sys.source("app.R", envir = env)
    if (slug == "power_explorer") stopifnot(!grepl("cost_base|cost_per_patient", as.character(env$ui)))
    env$server
  }
  shiny::testServer(app_server("power_explorer"), {
    do.call(session$setInputs, lab_input_defaults())
    do.call(session$setInputs, study_input_defaults())
    do.call(session$setInputs, teaching_case("pain_curves")$inputs)
    current_activity("pain_curves")
    session$setInputs(show_advanced = TRUE)
    stopifnot(planned()$n == 100, comparison()$cap_n == 100,
      identical(as.numeric(comparison_results()[[3]]), c(217, 124, 56)),
      identical(comparison_results()[[2]], c("59.2%", "82.8%", "99.2%")),
      !intervals_visible())
    has(report_sections()[["Sensitivity at the available sample"]], "100 per group")
    has(model_answers()$justification, "100 analyzable")
    session$setInputs(fixed_n = 60, recruit_cap = 500)
    stopifnot(comparison()$cap_n == 60)
    has(output$comparison_text, "60 analyzable")
    has(report_sections()[["Sensitivity at the available sample"]], "60 per group")
    has(model_answers()$justification, "60 analyzable")
    lacks(report_sections()[["Sensitivity at the available sample"]], "100 per group")
  })
  shiny::testServer(app_server("power_explorer"), {
    do.call(session$setInputs, lab_input_defaults())
    do.call(session$setInputs, study_input_defaults())
    session$setInputs(study_question = "My research question <kept exactly>", clinical_relevance = "My clinical rationale",
      participant_burden = "My burden assessment", evidence_sources = "My evidence", justification = "My conclusion",
      goal = "fixed", fixed_n = 17, dropout = .2, B = 100)
    has(report_paragraphs(), "17 per group; 34 total")
    has(report_paragraphs(), "22 per group; 44 total")
    lacks(report_paragraphs(), "Cost at")
    lacks(report_paragraphs(), "Costs in the entered currency")
    for (answer in c("My research question <kept exactly>", "My clinical rationale", "My burden assessment", "My evidence", "My conclusion")) has(report_paragraphs(), answer)
    has(report_sections()[["One simulated trial"]], "No single-trial simulation")
    session$setInputs(run_one = 1, run_many = 1)
    has(report_sections()[["One simulated trial"]], "Estimated difference:")
    has(report_sections()[["Many simulated trials"]], "100 simulated trials")
    session$setInputs(fixed_n = 31)
    has(report_paragraphs(), "31 per group; 62 total")
    has(report_sections()[["One simulated trial"]], "omitted")
    has(report_sections()[["Many simulated trials"]], "omitted")
    lacks(report_sections()[["Many simulated trials"]], "100 simulated trials")
    session$setInputs(run_one = 2, run_many = 2)
    has(report_sections()[["Many simulated trials"]], "100 simulated trials")
    current_activity("rehabilitation")
    has(report_sections()[["Many simulated trials"]], "different example")
    has(report_sections()[["Study context"]], teaching_case("rehabilitation")$title)
    session$setInputs(outcome = "proportions", missing_mode = "selective", missing_n = 60, run_one = 3, run_many = 3)
    has(report_sections()[["Simulation assumptions"]], "60 recruited")
    has(report_sections()[["Many simulated trials"]], "Estimated bias:")
    has(report_sections()[["One simulated trial"]], "observed outcomes")
    doc <- app_report_document("Report", "power_explorer", report_sections())
    has(doc, "&lt;kept exactly&gt;")
    stopifnot(lengths(regmatches(doc, gregexpr("Software: R", doc, fixed = TRUE))) == 1L,
      lengths(regmatches(doc, gregexpr("Teaching materials:", doc, fixed = TRUE))) == 1L)
    # Backup round trip restores all entered text and current controls, clears old results.
    path <- tempfile(fileext = ".json")
    writeLines(jsonlite::toJSON(list(schema = "sample-size-study-plan", version = 1, activity = "rehabilitation",
      inputs = current_lab_inputs(), study = study_details()), auto_unbox = TRUE), path)
    session$setInputs(upload_plan = data.frame(name = basename(path), size = file.info(path)$size, type = "application/json", datapath = path))
    stopifnot(is.null(one_saved()), is.null(many_saved()))
    restored <- read_study_plan(paste(readLines(path), collapse = "\n"))
    stopifnot(restored$study$justification == "My conclusion", restored$inputs$missing_n == 60)
    session$setInputs(study_design = "paired")
    has(report_paragraphs(), "design-specific sample-size method")
    lacks(report_paragraphs(), "Analyzable participants:")
    stopifnot(!"Many simulated trials" %in% names(report_sections()))
  })
  shiny::testServer(app_server("power_explorer"), {
    do.call(session$setInputs, lab_input_defaults())
    do.call(session$setInputs, study_input_defaults())
    current_activity("pain_one_many")
    import_status("Preserved on duplicate startup")
    session$setInputs(activity_request = list(activity = "pain_one_many", reset = FALSE, nonce = 1))
    stopifnot(import_status() == "Preserved on duplicate startup")
    session$setInputs(outcome = "proportions", goal = "fixed", fixed_n = 20, B = 5000, show_advanced = FALSE)
    stopifnot(pain_report(), report_heading() == "Pain relief: simulation report")
    has(report_paragraphs(), "20 patients per group (40 in total)")
    has(report_paragraphs(), "30% with duloxetine and 60% with neravixa")
    has(report_paragraphs(), "No single trial")
    lacks(report_paragraphs(), "Fixed study costs")
    stopifnot(!"Resources and feasibility" %in% names(report_sections()))
    has(model_answers()$justification, "20 patients per group")
    session$setInputs(run_one = 1, run_many = 1, justification = "My simulation reflection.")
    has(report_paragraphs(), "patients (" )
    has(report_paragraphs(), "latest batch contains 5000 independently simulated trials")
    has(report_paragraphs(), "percentage estimates power")
    lacks(report_paragraphs(), "confidence interval")
    stopifnot(!intervals_visible())
    lacks(report_paragraphs(), "My simulation reflection.")
    stopifnot(!"Your reflection" %in% names(report_sections()))
    session$setInputs(fixed_n = 56, run_many = 2)
    stopifnot(sample_comparison()$original$spec$n == 20,
      sample_comparison()$current$spec$n == 56, !is.null(output$distribution))
    has(report_sections()[["Comparing sample sizes"]], "first batch used 20")
    has(report_sections()[["Comparing sample sizes"]], "current batch uses 56")
    session$setInputs(show_advanced = TRUE, fixed_n = 50, plan_p0 = .4, plan_p1 = .7)
    has(report_paragraphs(), "50 patients per group (100 in total)")
    has(report_paragraphs(), "40% with duloxetine and 70% with neravixa")
    has(report_sections()[["One simulated trial"]], "earlier inputs")
    has(report_sections()[["Repeated simulated trials"]], "omitted")
    lacks(report_paragraphs(), "latest batch contains 5000")
    stopifnot(!"Comparing sample sizes" %in% names(report_sections()))
    has(model_answers()$justification, "50 patients per group")
    session$setInputs(reality = "null", run_one = 2, run_many = 3, study_question = "My additional question")
    stopifnot(is.null(sample_comparison()))
    has(report_paragraphs(), "the Type I error probability (false positives")
    has(report_paragraphs(), "My additional question")
    has(model_answers()$justification, "significant results are false positives")
    # Selected repetitions and comparison populations share the actual batch analyses.
    session$setInputs(show_advanced = FALSE, pain_population = "equal", compare_populations = TRUE,
      journey_repetitions = 12, B = 12, run_journey = 0)
    session$setInputs(run_journey = 1)
    saved <- many_saved()
    stopifnot(nrow(saved$results)==12, saved$spec$p_treatment==.3,
      saved$population_comparison$spec$p_treatment==.6, identical(saved$meta,snapshot()))
    sequence <- sequence_payload(saved)
    stopifnot(length(sequence$trials)==12)
    for(i in seq_len(12)) {
      t <- sequence$trials[[i]]
      check <- analyse_binary(t$counts[[2]],t$counts[[1]],saved$spec$n,.05)
      stopifnot(abs(t$p_value-check$p_value)<1e-12, t$reject==check$reject,
        abs(t$estimate-check$estimate)<1e-12)
    }
    has(report_sections()[["Comparison population"]], "60%")
    has(report_sections()[["Repeated simulated trials"]], "12 independently simulated trials")
    restored <- validate_lab_inputs(current_lab_inputs())
    stopifnot(restored$pain_population=="equal",restored$compare_populations,restored$journey_repetitions==12)
    session$setInputs(reset_trials=0)
    session$setInputs(reset_trials=1)
    stopifnot(is.null(one_saved()),is.null(many_saved()),is.null(baseline_many()),generating()$p_treatment==.3)
    session$setInputs(missing_mode = "selective")
    stopifnot(!pain_report(), "Resources and feasibility" %in% names(report_sections()))
  })
  shiny::testServer(app_server("prevalence_precision"), {
    session$setInputs(goal = "precision", anticipated_p = .20, full_width = .10, confidence = .95,
      unknown_p = FALSE, fixed_n = 246, dropout = 0, seed = 20260942)
    session$setInputs(justification = "My precision decision", simulate = 0)
    has(report_paragraphs(), "My precision decision")
    session$setInputs(goal = "fixed", fixed_n = 40, confidence = .90, anticipated_p = .8, unknown_p = FALSE, simulate = 1)
    has(report_paragraphs(), "events among 40")
    session$setInputs(fixed_n = 60)
    has(report_paragraphs(), "current analyzable count is 60")
    has(report_paragraphs(), "omitted")
    lacks(report_paragraphs(), "events among 40")
    session$setInputs(simulate = 2)
    has(report_paragraphs(), "events among 60")
    active_case("pilot_feasibility")
    has(report_paragraphs(), "different example")
    has(report_paragraphs(), "My precision decision")
  })
  shiny::testServer(app_server("sampling_distributions"), {
    session$setInputs(mu0 = 120, effect = -5, sigma = 10, n = 25, alpha = .05, sidedness = "less", interpretation = "My explanation")
    has(report_paragraphs(), "specified population mean 115")
    has(report_paragraphs(), "one-sided (decrease)")
    session$setInputs(effect = 0, n = 80)
    has(report_paragraphs(), "n = 80")
    has(report_paragraphs(), "Non-rejection probability under the null")
    lacks(report_paragraphs(), "Type II error probability =")
    has(report_paragraphs(), "My explanation")
  })
  message("App reports: current calculations, cases, all written answers, stale-result exclusion, missing outcomes, backup restoration and escaped downloads passed.")
}
if (identical(environment(), globalenv())) check_app_reports()
