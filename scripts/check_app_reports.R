check_app_reports <- function() {
  root <- getwd(); on.exit(setwd(root))
  source("R/sample_size_functions.R", local = TRUE)
  source("R/activity_bridge.R", local = TRUE)
  source("R/app_presentation.R", local = TRUE)
  has <- function(text, value) stopifnot(any(grepl(value, text, fixed = TRUE)))
  lacks <- function(text, value) stopifnot(!any(grepl(value, text, fixed = TRUE)))
  app_server <- function(slug) {
    setwd(file.path(root, "apps", slug))
    env <- new.env(parent = globalenv()); sys.source("app.R", envir = env); env$server
  }
  shiny::testServer(app_server("power_explorer"), {
    do.call(session$setInputs, lab_input_defaults())
    do.call(session$setInputs, study_input_defaults())
    session$setInputs(study_question = "My research question <kept exactly>", clinical_relevance = "My clinical rationale",
      participant_burden = "My burden assessment", evidence_sources = "My evidence", justification = "My conclusion",
      goal = "fixed", fixed_n = 17, dropout = .2, B = 100)
    has(report_paragraphs(), "17 per group; 34 total")
    has(report_paragraphs(), "22 per group; 44 total")
    for (answer in c("My research question <kept exactly>", "My clinical rationale", "My burden assessment", "My evidence", "My conclusion")) has(report_paragraphs(), answer)
    has(report_sections()[["One simulated study"]], "No single-study simulation")
    session$setInputs(run_one = 1, run_many = 1)
    has(report_sections()[["One simulated study"]], "Estimated difference:")
    has(report_sections()[["Many simulated studies"]], "100 simulated studies")
    session$setInputs(fixed_n = 31)
    has(report_paragraphs(), "31 per group; 62 total")
    has(report_sections()[["One simulated study"]], "omitted")
    has(report_sections()[["Many simulated studies"]], "omitted")
    lacks(report_sections()[["Many simulated studies"]], "100 simulated studies")
    session$setInputs(run_one = 2, run_many = 2)
    has(report_sections()[["Many simulated studies"]], "100 simulated studies")
    current_activity("rehabilitation")
    has(report_sections()[["Many simulated studies"]], "different example")
    has(report_sections()[["Study context"]], teaching_case("rehabilitation")$title)
    session$setInputs(outcome = "proportions", missing_mode = "selective", missing_n = 60, run_one = 3, run_many = 3)
    has(report_sections()[["Simulation assumptions"]], "60 recruited")
    has(report_sections()[["Many simulated studies"]], "Estimated bias:")
    has(report_sections()[["One simulated study"]], "observed outcomes")
    doc <- app_report_document("Report", "power_explorer", report_sections())
    has(doc, "&lt;kept exactly&gt;")
    stopifnot(lengths(regmatches(doc, gregexpr("Software: R", doc, fixed = TRUE))) == 1L,
      lengths(regmatches(doc, gregexpr("Teaching materials:", doc, fixed = TRUE))) == 1L)
    # Backup round trip restores all entered text and current controls, clears old results.
    path <- tempfile(fileext = ".json")
    writeLines(jsonlite::toJSON(list(schema = "sample-size-study-plan", version = 1, activity = "rehabilitation",
      inputs = current_lab_inputs(), study = study_details()), auto_unbox = TRUE), path)
    session$setInputs(upload_plan = data.frame(name = basename(path), size = file.info(path)$size, type = "application/json", datapath = path))
    stopifnot(is.null(one_saved()), is.null(many_saved()))
    restored <- read_study_plan(paste(readLines(path), collapse = "\n"))
    stopifnot(restored$study$justification == "My conclusion", restored$inputs$missing_n == 60)
    session$setInputs(study_design = "paired")
    has(report_paragraphs(), "design-specific sample-size method")
    lacks(report_paragraphs(), "Analyzable participants:")
    stopifnot(!"Many simulated studies" %in% names(report_sections()))
  })
  shiny::testServer(app_server("prevalence_precision"), {
    session$setInputs(goal = "precision", anticipated_p = .20, full_width = .10, confidence = .95,
      unknown_p = FALSE, fixed_n = 246, dropout = 0, seed = 20260942)
    session$setInputs(justification = "My precision decision", simulate = 0)
    has(report_paragraphs(), "My precision decision")
    session$setInputs(goal = "fixed", fixed_n = 40, confidence = .90, anticipated_p = .8, unknown_p = FALSE, simulate = 1)
    has(report_paragraphs(), "events among 40")
    session$setInputs(fixed_n = 60)
    has(report_paragraphs(), "current analyzable count is 60")
    has(report_paragraphs(), "omitted")
    lacks(report_paragraphs(), "events among 40")
    session$setInputs(simulate = 2)
    has(report_paragraphs(), "events among 60")
    active_case("pilot_feasibility")
    has(report_paragraphs(), "different example")
    has(report_paragraphs(), "My precision decision")
  })
  shiny::testServer(app_server("sampling_distributions"), {
    session$setInputs(mu0 = 120, effect = -5, sigma = 10, n = 25, alpha = .05, sidedness = "less", interpretation = "My explanation")
    has(report_paragraphs(), "specified population mean 115")
    has(report_paragraphs(), "one-sided (decrease)")
    session$setInputs(effect = 0, n = 80)
    has(report_paragraphs(), "n = 80")
    has(report_paragraphs(), "Non-rejection probability under the null")
    lacks(report_paragraphs(), "Type II error probability =")
    has(report_paragraphs(), "My explanation")
  })
  message("App reports: current calculations, cases, all written answers, stale-result exclusion, missing outcomes, backup restoration and escaped downloads passed.")
}
if (identical(environment(), globalenv())) check_app_reports()
